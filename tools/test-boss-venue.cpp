// Boss track shuffle (#169 tier 1, slot_data schema 18). Compiles the REAL
// parser (ap/ap_seedcfg.cpp is linked in) and the real decisions in
// ap/ap_boss_venue.h, and checks:
//
//   1. The shared fixture tools/fixtures/boss_venues.json (a byte-identical
//      copy of the apworld's worlds/ctr/test/fixtures/boss_venues.json)
//      equals this build's venue table, garage table and attack schedules.
//   2. Certification: every garage's retail attack fits every recorded track,
//      the home track maps onto itself, and a too-short track is refused.
//   3. Round trip: slot_data generated by the apworld with the option on and
//      off (tools/fixtures/boss-venue/) parses to the seed's four venues, or
//      to retail.
//   4. Refusals: every record shape this build cannot race refuses all four
//      encounters, never a retail fallback; a pre-18 seed is retail.
//   5. Isolation: the inherited-attack adapter runs only for a garage boss
//      race on its drawn venue, never on the home track, Oxide, a Gem Cup
//      leg or an ordinary race on the same track.
//
//   c++ -m32 -std=c++17 -DCTR_AP -Iap -Iap/vendor/json/include
//     tools/test-boss-venue.cpp ap/ap_seedcfg.cpp
//     -o /tmp/test-boss-venue && /tmp/test-boss-venue
//
// Run from the repository root (the fixture paths are relative to it).
// Exit 0 = every assertion held.

#include <cstdio>
#include <cstring>
#include <fstream>
#include <string>
#include <nlohmann/json.hpp>

#include "../ap/ap_seedcfg.h"
#include "../ap/ap_boss_venue.h"

extern void ap_seedcfg_parse_json(const nlohmann::json &j);

static int refusal_lines;
extern "C" void AP_LogLine(const char *line)
{
	if (std::strstr(line, "boss_encounters refused"))
		refusal_lines++;
}

static int checks;
static int failures;

static void expect(bool ok, const std::string &name)
{
	checks++;
	if (!ok)
	{
		failures++;
		std::printf("FAIL %s\n", name.c_str());
	}
}

static nlohmann::json load(const char *path)
{
	std::ifstream in(path);
	if (!in)
	{
		std::printf("FAIL cannot open %s\n", path);
		failures++;
		return nlohmann::json::object();
	}
	return nlohmann::json::parse(in);
}

static void check_fixture()
{
	const nlohmann::json fx = load("tools/fixtures/boss_venues.json");
	expect(fx.value("block_version", 0) == AP_BOSS_ENCOUNTERS_VERSION, "fixture block version");
	expect(fx["venues"].size() == AP_BOSS_VENUE_TRACKS, "fixture has 18 venues");
	for (const auto &v : fx["venues"])
	{
		int lid = v["level_id"].get<int>();
		expect(lid >= 0 && lid < AP_BOSS_VENUE_TRACKS &&
		           AP_BOSS_VENUE_RESTART_POINTS[lid] == v["restart_points"].get<int>(),
		       "restart points for " + v["name"].get<std::string>());
	}
	expect(fx["garages"].size() == AP_BOSS_VENUE_GARAGES, "fixture has four garages");
	for (const auto &g : fx["garages"])
	{
		int i = g["index"].get<int>();
		const AP_BossVenueGarage &row = AP_BOSS_VENUE_GARAGE[i];
		std::string key = g["key"].get<std::string>();
		expect(key == row.key, "garage key " + key);
		expect(g["location"].get<long>() == AP_BOSS_VENUE_LOCATION_BASE + i, "garage code " + key);
		expect(g["home_level_id"].get<int>() == row.homeLevel, "home track " + key);
		expect(g["attack_checkpoints"].size() == AP_BOSS_VENUE_SEGMENTS, "segment count " + key);
		for (int s = 0; s < AP_BOSS_VENUE_SEGMENTS; s++)
			expect(g["attack_checkpoints"][s].get<int>() == row.attack[s], "segment " + key);
	}
}

static void check_certification()
{
	for (int g = 0; g < AP_BOSS_VENUE_GARAGES; g++)
	{
		const AP_BossVenueGarage &row = AP_BOSS_VENUE_GARAGE[g];
		int homeLast = AP_BOSS_VENUE_RESTART_POINTS[row.homeLevel] - 1;
		for (int s = 0; s < AP_BOSS_VENUE_SEGMENTS; s++)
			expect(AP_BossVenueCheckpoint(row.attack[s], homeLast, homeLast) == row.attack[s],
			       std::string("home track maps to itself: ") + row.key);
		for (int lid = 0; lid < AP_BOSS_VENUE_TRACKS; lid++)
			expect(AP_BossVenueCertified(g, lid),
			       std::string(row.key) + " certified on track " + std::to_string(lid));
		expect(!AP_BossVenueCertified(g, 18), "LevelID 18 is not a venue");
		expect(!AP_BossVenueCertified(g, 110), "Cortex Vortex is not a tier-1 venue");
		expect(!AP_BossVenueScheduleFits(g, 4), "a four-checkpoint track cannot carry the attack");
	}
	// The apworld test pins the same numbers (translated_schedule).
	const int pin[] = {0, 6, 13, 19, 28};
	for (int s = 0; s < AP_BOSS_VENUE_SEGMENTS; s++)
		expect(AP_BossVenueCheckpoint(AP_BOSS_VENUE_GARAGE[3].attack[s], 174, 71) == pin[s],
		       "Pinstripe on Crash Cove keeps relative lap positions");
}

static void check_round_trip()
{
	nlohmann::json on = load("tools/fixtures/boss-venue/seed_on_slot_data.json");
	refusal_lines = 0;
	ap_seedcfg_parse_json(on);
	expect(ctr_cfg.schema_version == 18, "generated seed is schema 18 and admitted");
	expect(ctr_boss_encounters.state == AP_BOSS_ENC_VALID, "option-on seed parses");
	for (int g = 0; g < AP_BOSS_VENUE_GARAGES; g++)
	{
		int track = on["boss_encounters"]["garages"][AP_BOSS_VENUE_GARAGE[g].key]["track"].get<int>();
		expect(ctr_boss_encounters.track[g] == track, std::string("venue ") + AP_BOSS_VENUE_GARAGE[g].key);
		expect(AP_BossEncounterVenue(&ctr_boss_encounters, g) == track, "garage loads its drawn venue");
	}
	expect(refusal_lines == 0, "no refusal logged for a good seed");

	nlohmann::json off = load("tools/fixtures/boss-venue/seed_off_slot_data.json");
	ap_seedcfg_parse_json(off);
	expect(ctr_boss_encounters.state == AP_BOSS_ENC_RETAIL, "option-off seed is retail");
	for (int g = 0; g < AP_BOSS_VENUE_GARAGES; g++)
		expect(AP_BossEncounterVenue(&ctr_boss_encounters, g) == AP_BOSS_VENUE_GARAGE[g].homeLevel,
		       "retail seed loads the home track");
}

template <typename F>
static void refused(const char *name, F mutate)
{
	nlohmann::json sd = load("tools/fixtures/boss-venue/seed_on_slot_data.json");
	mutate(sd);
	refusal_lines = 0;
	ap_seedcfg_parse_json(sd);
	expect(ctr_boss_encounters.state == AP_BOSS_ENC_REFUSED, std::string("refused: ") + name);
	expect(refusal_lines == 1, std::string("one log line: ") + name);
	expect(ctr_boss_encounters.reason[0] != 0, std::string("reason kept: ") + name);
	for (int g = 0; g < AP_BOSS_VENUE_GARAGES; g++)
		expect(AP_BossEncounterVenue(&ctr_boss_encounters, g) == -1,
		       std::string("no retail fallback: ") + name);
}

static void check_refusals()
{
	auto row = [](nlohmann::json &sd, const char *k) -> nlohmann::json & {
		return sd["boss_encounters"]["garages"][k];
	};
	refused("switch on, block missing", [](nlohmann::json &sd) { sd.erase("boss_encounters"); });
	refused("block present, switch off", [](nlohmann::json &sd) { sd["ctr_options"]["boss_track_shuffle"] = false; });
	refused("block present, switch absent", [](nlohmann::json &sd) { sd["ctr_options"].erase("boss_track_shuffle"); });
	refused("switch not boolean", [](nlohmann::json &sd) { sd["ctr_options"]["boss_track_shuffle"] = 1; });
	refused("block not object", [](nlohmann::json &sd) { sd["boss_encounters"] = nlohmann::json::array(); });
	refused("newer block version", [](nlohmann::json &sd) { sd["boss_encounters"]["version"] = 2; });
	refused("garage missing", [](nlohmann::json &sd) { sd["boss_encounters"]["garages"].erase("pinstripe"); });
	refused("extra garage", [&](nlohmann::json &sd) { sd["boss_encounters"]["garages"]["oxide"] = row(sd, "pinstripe"); });
	refused("wrong code", [&](nlohmann::json &sd) { row(sd, "papu_papu")["location"] = 35011100; });
	refused("wrong home", [&](nlohmann::json &sd) { row(sd, "papu_papu")["home_track"] = 6; });
	refused("unknown track", [&](nlohmann::json &sd) { row(sd, "komodo_joe")["track"] = 110; });
	refused("track as string", [&](nlohmann::json &sd) { row(sd, "komodo_joe")["track"] = "3"; });
	refused("opponent swap", [&](nlohmann::json &sd) { row(sd, "ripper_roo")["opponent"] = "crash"; });
	refused("AI profile", [&](nlohmann::json &sd) { row(sd, "ripper_roo")["ai_profile"] = "boss_grade"; });
	refused("composed kit", [&](nlohmann::json &sd) { row(sd, "ripper_roo")["attack"] = "composed"; });
	refused("package pin", [&](nlohmann::json &sd) { row(sd, "ripper_roo")["packages"] = nlohmann::json::array({"x"}); });
	refused("extra row field", [&](nlohmann::json &sd) { row(sd, "ripper_roo")["schedule"] = 1; });
	refused("missing row field", [&](nlohmann::json &sd) { row(sd, "ripper_roo").erase("packages"); });

	// A pre-18 seed never draws: its boss fields are not read at all.
	nlohmann::json legacy = load("tools/fixtures/boss-venue/seed_on_slot_data.json");
	legacy["ctr_options"]["schema_version"] = 17;
	refusal_lines = 0;
	ap_seedcfg_parse_json(legacy);
	expect(ctr_boss_encounters.state == AP_BOSS_ENC_RETAIL, "schema 17 is retail");
	expect(refusal_lines == 0, "schema 17 logs no refusal");

	// A refused seed followed by a good one does not inherit the refusal.
	nlohmann::json good = load("tools/fixtures/boss-venue/seed_on_slot_data.json");
	ap_seedcfg_parse_json(good);
	expect(ctr_boss_encounters.state == AP_BOSS_ENC_VALID, "next parse starts clean");
}

static void check_isolation()
{
	AP_BossEncounters e;
	std::memset(&e, 0, sizeof e);
	e.state = AP_BOSS_ENC_VALID;
	e.track[0] = 3;  // Roo on Crash Cove
	e.track[1] = 5;  // Papu stays home
	e.track[2] = 13; // Joe on Oxide Station
	e.track[3] = 17; // Pinstripe on Turbo Track

	expect(AP_BossEncounterShuffledGarage(&e, 1, 0, 0, 3) == 0, "Roo on his drawn venue");
	expect(AP_BossEncounterShuffledGarage(&e, 1, 0, 1, 5) == -1, "Papu at home uses the retail path");
	expect(AP_BossEncounterShuffledGarage(&e, 1, 0, 2, 13) == 2, "Joe on Oxide Station");
	expect(AP_BossEncounterShuffledGarage(&e, 1, 0, 4, 13) == -1, "Oxide's own race is never adapted");
	expect(AP_BossEncounterShuffledGarage(&e, 1, 0, 5, 13) == -1, "Oxide's final race is never adapted");
	expect(AP_BossEncounterShuffledGarage(&e, 0, 0, 0, 3) == -1, "an ordinary Crash Cove race");
	expect(AP_BossEncounterShuffledGarage(&e, 0, 1, 0, 3) == -1, "a Gem Cup leg on the same track");
	expect(AP_BossEncounterShuffledGarage(&e, 1, 1, 0, 3) == -1, "a cup flag wins over a stale boss flag");
	expect(AP_BossEncounterShuffledGarage(&e, 1, 0, 0, 6) == -1, "stale bossID on another track");

	e.state = AP_BOSS_ENC_RETAIL;
	expect(AP_BossEncounterShuffledGarage(&e, 1, 0, 0, 3) == -1, "retail seed never adapts");
	e.state = AP_BOSS_ENC_REFUSED;
	expect(AP_BossEncounterShuffledGarage(&e, 1, 0, 0, 3) == -1, "refused seed never adapts");
	expect(AP_BossEncounterVenue(&e, 0) == -1, "refused seed loads nothing");
	expect(AP_BossEncounterVenue(nullptr, 2) == AP_BOSS_VENUE_GARAGE[2].homeLevel, "no seed is retail");
	expect(AP_BossEncounterVenue(&e, 4) == -1, "Oxide is not a drawn garage");
}

int main()
{
	check_fixture();
	check_certification();
	check_round_trip();
	check_refusals();
	check_isolation();
	std::printf("%s: %d checks, %d failures\n", failures ? "FAIL" : "PASS", checks, failures);
	return failures ? 1 : 0;
}
