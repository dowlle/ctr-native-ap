#!/usr/bin/env python3
"""Copy or compare the apworld's generated track fill catalogue."""

import argparse
import json
from pathlib import Path


def catalogue(root):
    return {file.relative_to(root): file.read_bytes() for file in root.glob("*/*.json")}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("apworld", type=Path, help="apworld source checkout")
    parser.add_argument("--check", action="store_true", help="compare instead of copying")
    args = parser.parse_args()
    source = catalogue(args.apworld / "worlds/ctr/data/track_fill")
    root = Path(__file__).resolve().parents[1]
    dest = root / "assets/track_fill"
    index = root / "ap/ap_track_fill_index.inc"
    existing = catalogue(dest)
    if not source:
        parser.error("the apworld has no track fill files")
    rows = []
    for relative, data in sorted(source.items()):
        fill = json.loads(data)
        sha = fill["lev_sha256"]
        if relative.stem != sha[:16]:
            parser.error(f"track fill pin differs from path: {relative}")
        values = (sha, relative.as_posix(), fill["fill_sha256"])
        rows.append("    {" + ", ".join(map(json.dumps, values)) + "},\n")
    index_data = "// Generated by tools/sync-track-fill.py.\n" + "".join(rows)
    if args.check:
        if existing != source or not index.exists() or index.read_text() != index_data:
            parser.exit(1, "client catalogue differs from the apworld\n")
    else:
        retired = existing.keys() - source.keys()
        if retired:
            parser.error("the client still has retired files: " + ", ".join(map(str, sorted(retired))))
        for relative, data in source.items():
            path = dest / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        index.write_text(index_data)
    print(f"{len(source)} track fill files")


if __name__ == "__main__":
    main()
